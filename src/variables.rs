pub fn print_variables(){
    let mut x = 5;
    println!("The value of x is: {}", x);
    x = 6;
    println!("The value of x is: {}", x);
}

pub fn add_variables() {
    let mut x = 5;
    println!("The value of x is: {}", x);
    x = x + 1;
    println!("The value of x is: {}", x);
    x = x * 2;
    println!("The value of x is: {}", x);
}